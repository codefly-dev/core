// protoc plugin `protoc-gen-codefly-facade-ts`.
//
// For every proto package with services it emits one <module>_facade.ts next to
// the protoc-gen-es output, importing the generated service schemas. Each
// facade exposes a `New(transport)` entry point whose accessors return
// connect-es clients — which already take and return plain messages, so no
// per-method wrapping is needed:
//
//     import { accounts } from "./accounts_facade.js";
//     const client = accounts.New(transport).audit();
//     await client.queryAuditLog({ pageSize: 20 });
import { createEcmaScriptPlugin } from "@bufbuild/protoplugin";

const VERSION_SEGMENT = /^v\d+$/;

function packageOf(service) {
  const i = service.typeName.lastIndexOf(".");
  return i < 0 ? "" : service.typeName.slice(0, i);
}

function defaultModuleName(pkg) {
  const segments = pkg.split(".").filter((s) => s && !VERSION_SEGMENT.test(s));
  return segments.length ? segments[segments.length - 1] : pkg.replace(/\./g, "_");
}

function camel(name) {
  return name ? name[0].toLowerCase() + name.slice(1) : name;
}

function pascal(name) {
  return name ? name[0].toUpperCase() + name.slice(1) : name;
}

function accessorName(serviceName) {
  return camel(serviceName.replace(/Service$/, ""));
}

function parseOptions(raw) {
  const options = { services: null, module: undefined };
  for (const { key, value } of raw) {
    switch (key) {
      case "services":
        options.services = new Set(value.split("+").filter(Boolean));
        break;
      case "module":
        options.module = value;
        break;
      default:
        throw new Error(`unknown plugin option "${key}"`);
    }
  }
  return options;
}

function dirOf(name) {
  const i = name.lastIndexOf("/");
  return i < 0 ? "" : name.slice(0, i + 1);
}

function generateTs(schema) {
  // Group the target services by proto package: a service's fully-qualified
  // name — hence its facade — is per package.
  const groups = new Map();
  const order = [];
  for (const file of schema.files) {
    for (const service of file.services) {
      if (schema.options.services && !schema.options.services.has(service.name)) {
        continue;
      }
      const pkg = packageOf(service);
      if (!groups.has(pkg)) {
        groups.set(pkg, { file, services: [] });
        order.push(pkg);
      }
      groups.get(pkg).services.push(service);
    }
  }

  if (schema.options.services) {
    const available = new Set();
    for (const file of schema.files) {
      for (const service of file.services) available.add(service.name);
    }
    const unknown = [...schema.options.services].filter((s) => !available.has(s));
    if (unknown.length) {
      throw new Error(`declared services not found in the proto: ${unknown.sort().join(", ")}`);
    }
  }

  const moduleNames = new Map();
  const single = order.length === 1;
  for (const pkg of order) {
    const { file, services } = groups.get(pkg);
    const module = schema.options.module && single ? schema.options.module : defaultModuleName(pkg);
    if (moduleNames.has(module)) {
      throw new Error(`module name collision: packages ${pkg} and ${moduleNames.get(module)} both map to ${module}`);
    }
    moduleNames.set(module, pkg);
    emit(schema, file, services, pkg, module);
  }
}

function emit(schema, file, services, pkg, module) {
  const g = schema.generateFile(`${dirOf(file.name)}${module}_facade.ts`);
  g.print(`// generated by protoc-gen-codefly-facade-ts from ${pkg}; do not edit`);
  g.print();

  const createClient = g.import("createClient", "@connectrpc/connect");
  const Transport = g.import("Transport", "@connectrpc/connect", true);

  const accessors = new Map();
  for (const service of services) {
    const accessor = accessorName(service.name);
    if (accessors.has(accessor)) {
      throw new Error(`service accessor collision: ${service.name} and ${accessors.get(accessor)} both map to ${accessor}()`);
    }
    accessors.set(accessor, service.name);
  }

  g.print(g.export("const", module), " = {");
  g.print("  New(transport: ", Transport, ") {");
  g.print("    return {");
  for (const service of services) {
    const schemaImport = g.importSchema(service);
    g.print("      ", accessorName(service.name), ": () => ", createClient, "(", schemaImport, ", transport),");
  }
  g.print("    };");
  g.print("  },");
  g.print("};");
  g.print();
  g.print(g.export("type", `${pascal(module)}Client`), " = ReturnType<typeof ", module, ".New>;");
}

export const protocGenCodeflyFacadeTs = createEcmaScriptPlugin({
  name: "protoc-gen-codefly-facade-ts",
  version: "v0.0.13",
  parseOptions,
  generateTs,
});
