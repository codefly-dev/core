// What Buf owns in a generated output root.
//
// An output root such as code/pkg/gen is shared: Buf writes the bindings, and
// other generators place their own files beside them — `codefly generate
// permissions` writes pkg/gen/permissions, because pkg/gen is where a Go
// service's generated code lives. A file says which generator wrote it with the
// generated-code notice (`Code generated by <generator>. DO NOT EDIT.`), and
// every protoc plugin Buf runs names itself protoc-gen-*. So Buf owns every
// file in its output roots except one whose notice names another generator:
// that file is regenerated by its own generator and Buf neither removes nor
// replaces it. A file with no notice (an OpenAPI document, a stale copy) is
// Buf's, as it always was.

// noticeWindow bounds how much of a file is read for its leading notice: the
// notice and a binding's source line sit in its first comment block.
const noticeWindow = 8 << 10

var (
	generatedNotice = regexp.MustCompile(`^(?://|#) Code generated by (\S.*?)\. DO NOT EDIT\.$`)
	// protoc-gen-go, -go-grpc and -grpc-gateway write `// source: <file>`,
	// protoc-gen-connect-go `// Source: <file>`: the proto file the binding is
	// generated from, named as Buf names it.
	bindingSource = regexp.MustCompile(`^// [Ss]ource: (\S+\.proto)$`)
)

// fileNotice is what a file's leading comment block says about who wrote it.
type fileNotice struct {
	generator string // "" when the file carries no generated-code notice
	source    string // the proto file a binding is generated from, "" when none is named
}

// readNotice reads the generated-code notice and the binding source from the
// comment lines a file starts with. It stops at the first line that is not a
// comment, so a notice quoted in a file's body is never mistaken for its own.
func readNotice(file string) (fileNotice, error) {
	handle, err := os.Open(file)
	if err != nil {
		return fileNotice{}, err
	}
	defer func() { _ = handle.Close() }()
	var notice fileNotice
	scanner := bufio.NewScanner(io.LimitReader(handle, noticeWindow))
	for scanner.Scan() {
		line := strings.TrimRight(scanner.Text(), "\r")
		if line == "" {
			continue
		}
		if !strings.HasPrefix(line, "//") && !strings.HasPrefix(line, "#") {
			break
		}
		if match := generatedNotice.FindStringSubmatch(line); match != nil && notice.generator == "" {
			notice.generator = match[1]
		}
		if match := bindingSource.FindStringSubmatch(line); match != nil && notice.source == "" {
			notice.source = match[1]
		}
	}
	if err := scanner.Err(); err != nil && !errors.Is(err, bufio.ErrTooLong) {
		return fileNotice{}, err
	}
	return notice, nil
}

// ownedByAnotherGenerator reports whether a file in a Buf output root was
// written by a generator other than a protoc plugin.
func ownedByAnotherGenerator(file string) (bool, error) {
	info, err := os.Lstat(file)
	if err != nil {
		return false, err
	}
	if !info.Mode().IsRegular() {
		return false, nil
	}
	notice, err := readNotice(file)
	if err != nil {
		return false, err
	}
	return notice.generator != "" && !strings.HasPrefix(notice.generator, "protoc-gen-"), nil
}

// clearGeneratedDir empties a Buf output root of everything Buf owns, keeping
// the root itself and every file another generator owns.
func clearGeneratedDir(root string) error {
	if _, err := os.Lstat(root); errors.Is(err, fs.ErrNotExist) {
		return nil
	} else if err != nil {
		return err
	}
	err := filepath.WalkDir(root, func(file string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			return nil
		}
		kept, err := ownedByAnotherGenerator(file)
		if err != nil {
			return err
		}
		if kept {
			return nil
		}
		return os.Remove(file)
	})
	if err != nil {
		return err
	}
	return pruneEmptyDirs(root)
}

// pruneEmptyDirs removes every directory below root left with nothing in it.
func pruneEmptyDirs(root string) error {
	if _, err := os.Lstat(root); errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	var dirs []string
	err := filepath.WalkDir(root, func(dir string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() && dir != root {
			dirs = append(dirs, dir)
		}
		return nil
	})
	if err != nil {
		return err
	}
	// Deepest first, so a parent is judged after its children are gone.
	sort.Slice(dirs, func(i, j int) bool { return len(dirs[i]) > len(dirs[j]) })
	for _, dir := range dirs {
		entries, err := os.ReadDir(dir)
		if err != nil {
			return err
		}
		if len(entries) == 0 {
			if err := os.Remove(dir); err != nil {
				return err
			}
		}
	}
	return nil
}

// A service's Go bindings own no foreign file.
//
// A service vendors codefly's protos and the authority's hop option under its
// own proto tree so its contract compiles, and buf generates every file of its
// module, so the vendored files came out as a second set of Go bindings — the
// same files core and the hop library register, emitted again into the
// service. IsForeignFile is the rule a generated Go library already follows;
// the service's Go output follows it too. buf cannot drop a file for one
// plugin and keep it for another (a template generating TypeScript beside Go
// still owns a TypeScript copy of codefly's protos), so the Go bindings of a
// foreign file are removed from the Go output roots once buf has written them,
// before anything reads or formats that output.

// localFilesImage is the descriptor set of the module's own files, written to
// the generator directory for the length of one generation.
const localFilesImage = ".codefly-local-files.binpb"

// goBinding is one generated Go file and the proto file it was generated from.
type goBinding struct {
	file   string
	source string
}

// goBindings returns the generated Go files under roots that name the proto
// file they were generated from.
func goBindings(roots []string) ([]goBinding, error) {
	var bindings []goBinding
	for _, root := range roots {
		files, err := generatedGoFiles(root)
		if err != nil {
			return nil, err
		}
		for _, file := range files {
			notice, err := readNotice(file)
			if err != nil {
				return nil, err
			}
			if notice.source != "" {
				bindings = append(bindings, goBinding{file: file, source: notice.source})
			}
		}
	}
	return bindings, nil
}

// inForeignNamespacePath reports whether a proto file name lies under the path
// of a foreign namespace. The path alone never decides (see foreignNamespace):
// it only says whether the package has to be read at all.
func inForeignNamespacePath(name string) bool {
	for _, ns := range foreignNamespaces {
		if strings.HasPrefix(name, ns.pathPrefix) {
			return true
		}
	}
	return false
}

// foreignGoFiles returns the names of the files in set a Go binding must not own.
func foreignGoFiles(set *descriptorpb.FileDescriptorSet) map[string]bool {
	foreign := map[string]bool{}
	for _, file := range set.GetFile() {
		if IsForeignFile(file, languages.GO) {
			foreign[file.GetName()] = true
		}
	}
	return foreign
}

// removeForeignBindings removes every binding generated from a foreign file and
// the directories that leaves empty below each root.
func removeForeignBindings(roots []string, bindings []goBinding, foreign map[string]bool) error {
	removed := false
	for _, binding := range bindings {
		if !foreign[binding.source] {
			continue
		}
		if err := os.Remove(binding.file); err != nil {
			return fmt.Errorf("remove Go binding of foreign %s: %w", binding.source, err)
		}
		removed = true
	}
	if !removed {
		return nil
	}
	for _, root := range roots {
		if err := pruneEmptyDirs(root); err != nil {
			return err
		}
	}
	return nil
}

// removeForeignGoBindings reads the module's own files from buf and removes the
// Go bindings generated for the foreign ones. hostRoot is mounted at
// containerRoot for a companion; containerRoot is "" for a host backend.
func (g *Buf) removeForeignGoBindings(ctx context.Context, runner ProcessRunner, templateDir, templateName, hostRoot, containerRoot string) error {
	roots, err := GoOutputRoots(templateDir, templateName)
	if err != nil {
		return fmt.Errorf("discover generated Go outputs: %w", err)
	}
	bindings, err := goBindings(roots)
	if err != nil {
		return fmt.Errorf("inspect generated Go: %w", err)
	}
	candidate := false
	for _, binding := range bindings {
		if inForeignNamespacePath(binding.source) {
			candidate = true
			break
		}
	}
	if !candidate {
		return nil
	}

	hostImage := filepath.Join(hostRoot, localFilesImage)
	runnerImage := hostImage
	if containerRoot != "" {
		runnerImage = path.Join(containerRoot, localFilesImage)
	}
	defer func() { _ = os.Remove(hostImage) }()
	proc, err := runner.NewProcess("buf", "build", "--exclude-imports", "--as-file-descriptor-set", "-o", runnerImage)
	if err != nil {
		return fmt.Errorf("create buf build process: %w", err)
	}
	if err = proc.Run(ctx); err != nil {
		return fmt.Errorf("build the module's descriptors: %w", err)
	}
	data, err := os.ReadFile(hostImage)
	if err != nil {
		return fmt.Errorf("read the module's descriptors: %w", err)
	}
	var set descriptorpb.FileDescriptorSet
	if err = googleproto.Unmarshal(data, &set); err != nil {
		return fmt.Errorf("decode the module's descriptors: %w", err)
	}
	return removeForeignBindings(roots, bindings, foreignGoFiles(&set))
}
