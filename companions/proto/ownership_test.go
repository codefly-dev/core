func writeFile(t *testing.T, file, contents string) {
	t.Helper()
	require.NoError(t, os.MkdirAll(filepath.Dir(file), 0o755))
	require.NoError(t, os.WriteFile(file, []byte(contents), 0o644))
}

// `codefly generate permissions` writes its table into the service's pkg/gen,
// beside Buf's bindings. Cleaning Buf's output before a generation must leave
// that table alone, or every sync deletes it and the service stops compiling.
func TestBufCleanGeneratedDirsKeepsAnotherGeneratorsFiles(t *testing.T) {
	root := t.TempDir()
	generated := filepath.Join(root, "code", "pkg", "gen")
	permissionsGo := "// Code generated by codefly generate permissions. DO NOT EDIT.\npackage permissions\n"
	permissionsTS := "// Code generated by codefly generate permissions. DO NOT EDIT.\nexport const Permission = {};\n"
	writeFile(t, filepath.Join(generated, "permissions", "permissions_gen.go"), permissionsGo)
	writeFile(t, filepath.Join(generated, "permissions", "permissions_gen.ts"), permissionsTS)
	// Buf's own bindings, a stale one from a renamed package among them.
	writeFile(t, filepath.Join(generated, "records", "v1", "api.pb.go"), "// Code generated by protoc-gen-go. DO NOT EDIT.\n// source: records/v1/api.proto\n\npackage v1\n")
	writeFile(t, filepath.Join(generated, "old", "v0", "genconnect", "api.connect.go"), "// Code generated by protoc-gen-connect-go. DO NOT EDIT.\n//\n// Source: old/v0/api.proto\n\npackage genconnect\n")
	// No notice: Buf's, as before.
	writeFile(t, filepath.Join(generated, "api.swagger.json"), "{}\n")
	// A notice quoted in the body is not the file's own.
	writeFile(t, filepath.Join(generated, "quoted", "doc.go"), "package quoted\n\n// Code generated by codefly generate permissions. DO NOT EDIT.\n")
	require.NoError(t, os.Symlink(filepath.Join(generated, "permissions", "permissions_gen.go"), filepath.Join(generated, "linked.go")))

	generator, err := NewBuf(context.Background(), root)
	require.NoError(t, err)
	generator.WithGeneratedDirs(generated)
	require.NoError(t, generator.cleanGeneratedDirs())

	var left []string
	require.NoError(t, filepath.Walk(generated, func(file string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(generated, file)
		left = append(left, filepath.ToSlash(rel))
		return nil
	}))
	require.Equal(t, []string{".", "permissions", "permissions/permissions_gen.go", "permissions/permissions_gen.ts"}, left)
	got, err := os.ReadFile(filepath.Join(generated, "permissions", "permissions_gen.go"))
	require.NoError(t, err)
	require.Equal(t, permissionsGo, string(got))
}

func fileDescriptor(name, pkg string) *descriptorpb.FileDescriptorProto {
	return &descriptorpb.FileDescriptorProto{Name: googleproto.String(name), Package: googleproto.String(pkg)}
}

// A service vendors codefly's protos and the hop option to compile; buf
// generates every file of the module, so their Go bindings came out again in
// the service. IsForeignFile decides — codefly's by path and package together,
// the hop's by its go_package lying in a module the service's go.mod requires —
// and only Go output is touched. The module's own file under the hop's path
// stays its own.
func TestRemoveForeignBindingsKeepsTheServicesOwnGo(t *testing.T) {
	root := t.TempDir()
	goOut := filepath.Join(root, "code", "pkg", "gen")
	writeFile(t, filepath.Join(root, "code", "go.mod"), "module github.com/acme/records/code\n\ngo 1.24\n\nrequire (\n\tgithub.com/codefly-dev/authority/libraries/hop/go v0.0.0-20261024000000-bc4d12956a06\n\tgithub.com/codefly-dev/core v0.19.6\n)\n")
	tsOut := filepath.Join(root, "frontend", "gen")
	binding := func(rel, generator, sourceLine string) string {
		file := filepath.Join(goOut, rel)
		writeFile(t, file, "// Code generated by "+generator+". DO NOT EDIT.\n// versions:\n// \tprotoc-gen-go v1.36.11\n"+sourceLine+"\n\npackage x\n")
		return file
	}
	own := binding("records/v1/api.pb.go", "protoc-gen-go", "// source: records/v1/api.proto")
	ownGRPC := binding("records/v1/api_grpc.pb.go", "protoc-gen-go-grpc", "// source: records/v1/api.proto")
	ownConnect := binding("records/v1/genconnect/api.connect.go", "protoc-gen-connect-go", "// Source: records/v1/api.proto")
	// A file the module keeps under codefly/ in its own package is its own.
	ownUnderCodefly := binding("codefly/notes/notes.pb.go", "protoc-gen-go", "// source: codefly/notes/notes.proto")
	binding("codefly/base/v0/agent.pb.go", "protoc-gen-go", "// source: codefly/base/v0/agent.proto")
	binding("codefly/runnable/v0/options.pb.go", "protoc-gen-go", "// source: codefly/runnable/v0/options.proto")
	binding("authority/hop/v1/policy.pb.go", "protoc-gen-go", "// source: authority/hop/v1/policy.proto")
	binding("authority/hop/v1/genconnect/policy.connect.go", "protoc-gen-connect-go", "// Source: authority/hop/v1/policy.proto")
	ownUnderHop := binding("authority/hop/v1/notes.pb.go", "protoc-gen-go", "// source: authority/hop/v1/notes.proto")
	permissions := filepath.Join(goOut, "permissions", "permissions_gen.go")
	writeFile(t, permissions, "// Code generated by codefly generate permissions. DO NOT EDIT.\npackage permissions\n")
	// TypeScript still owns its copy of codefly's protos.
	tsCopy := filepath.Join(tsOut, "codefly", "base", "v0", "agent_pb.ts")
	writeFile(t, tsCopy, "// @generated by protoc-gen-es v2.2.3\n// source: codefly/base/v0/agent.proto\nexport {};\n")

	set := &descriptorpb.FileDescriptorSet{File: []*descriptorpb.FileDescriptorProto{
		fileDescriptor("records/v1/api.proto", "records.v1"),
		fileDescriptor("codefly/notes/notes.proto", "records.notes"),
		fileDescriptor("codefly/base/v0/agent.proto", "codefly.base.v0"),
		fileDescriptor("codefly/runnable/v0/options.proto", "codefly.runnable.v0"),
		withGoPackage(fileDescriptor("authority/hop/v1/policy.proto", "authority.hop.v1"), "github.com/codefly-dev/authority/libraries/hop/go/gen/authority/hop/v1;hopv1"),
		withGoPackage(fileDescriptor("authority/hop/v1/notes.proto", "authority.hop.v1"), "github.com/acme/records/code/pkg/gen/authority/hop/v1;hopv1"),
	}}
	roots := []string{goOut}
	bindings, err := goBindings(roots)
	require.NoError(t, err)
	require.Len(t, bindings, 9)
	requires, err := goRequires(goOut)
	require.NoError(t, err)
	require.NoError(t, removeForeignBindings(roots, bindings, foreignGoFiles(set, requires)))

	for _, kept := range []string{own, ownGRPC, ownConnect, ownUnderCodefly, ownUnderHop, permissions, tsCopy} {
		require.FileExists(t, kept)
	}
	for _, gone := range []string{"codefly/base", "codefly/runnable", "authority/hop/v1/genconnect", "authority/hop/v1/policy.pb.go"} {
		require.NoFileExists(t, filepath.Join(goOut, gone))
		require.NoDirExists(t, filepath.Join(goOut, gone))
	}
}

// A service whose go.mod requires no module the hop's go_package lies in does
// not import the hop's bindings from one, so its own copy is its own.
func TestAVendoredFileIsForeignOnlyByADependencyTheServiceDeclares(t *testing.T) {
	root := t.TempDir()
	goOut := filepath.Join(root, "code", "pkg", "gen")
	writeFile(t, filepath.Join(root, "code", "go.mod"), "module github.com/acme/records/code\n\ngo 1.24\n")
	policy := filepath.Join(goOut, "authority", "hop", "v1", "policy.pb.go")
	writeFile(t, policy, "// Code generated by protoc-gen-go. DO NOT EDIT.\n// source: authority/hop/v1/policy.proto\n\npackage x\n")
	set := &descriptorpb.FileDescriptorSet{File: []*descriptorpb.FileDescriptorProto{
		withGoPackage(fileDescriptor("authority/hop/v1/policy.proto", "authority.hop.v1"), "github.com/codefly-dev/authority/libraries/hop/go/gen/authority/hop/v1;hopv1"),
	}}
	bindings, err := goBindings([]string{goOut})
	require.NoError(t, err)
	requires, err := goRequires(goOut)
	require.NoError(t, err)
	require.Empty(t, requires)
	require.NoError(t, removeForeignBindings([]string{goOut}, bindings, foreignGoFiles(set, requires)))
	require.FileExists(t, policy)
	// No go.mod at all governs nothing and requires nothing.
	requires, err = goRequires(t.TempDir())
	require.NoError(t, err)
	require.Empty(t, requires)
}

// TestANestedModuleRequiringItsParentClassesItsOwnGoPackageForeign pins
// today's classification of a nested Go module, a known gap (review r4 f7 of
// core#835): foreignByGoPackage prefix-matches go_package against the requires
// of the governing go.mod and never consults that go.mod's own module path,
// so a module github.com/acme/repo/services/api that requires its parent
// github.com/acme/repo classes its own go_package as the parent's, and its own
// bindings would be removed. Go's rule is the longest module prefix, which
// would keep them. No fleet repository generates through this path from such a
// layout today (module-tracing's nested clients/go/read requires its parent,
// but generates with buf directly and its proto's go_package lies outside the
// parent). This test fails the day the classification changes, so that change
// is made on purpose, with this expectation turned around.
func TestANestedModuleRequiringItsParentClassesItsOwnGoPackageForeign(t *testing.T) {
	root := t.TempDir()
	service := filepath.Join(root, "services", "api")
	writeFile(t, filepath.Join(service, "go.mod"), "module github.com/acme/repo/services/api\n\ngo 1.24\n\nrequire github.com/acme/repo v0.1.0\n")
	requires, err := goRequires(filepath.Join(service, "gen"))
	require.NoError(t, err)
	require.Equal(t, []string{"github.com/acme/repo"}, requires)
	own := withGoPackage(fileDescriptor("api/v1/api.proto", "api.v1"), "github.com/acme/repo/services/api/gen/api/v1;apiv1")
	require.True(t, foreignByGoPackage(own, requires), "today the nested module's own go_package reads as its parent's")
	parent := withGoPackage(fileDescriptor("shared/v1/shared.proto", "shared.v1"), "github.com/acme/repo/gen/shared/v1;sharedv1")
	require.True(t, foreignByGoPackage(parent, requires), "the parent's own go_package is foreign, rightly")
}

func withGoPackage(file *descriptorpb.FileDescriptorProto, goPackage string) *descriptorpb.FileDescriptorProto {
	file.Options = &descriptorpb.FileOptions{GoPackage: googleproto.String(goPackage)}
	return file
}

func TestOnlyAForeignNamespacePathNeedsItsPackageRead(t *testing.T) {
	require.True(t, inForeignNamespacePath("codefly/base/v0/agent.proto"))
	require.True(t, inForeignNamespacePath("google/api/annotations.proto"))
	require.False(t, inForeignNamespacePath("authority/hop/v1/policy.proto"), "core's namespace table names no host")
	require.False(t, inForeignNamespacePath("records/v1/api.proto"))
	require.False(t, inForeignNamespacePath("authority/v1/issuer.proto"))
}

// The module's descriptors are read only when a binding could be foreign: by
// a namespace path, or by a go_package its source declares in a required
// module. An unreadable source is a candidate, since only descriptors decide.
func TestADeclaredGoPackageMakesABindingACandidate(t *testing.T) {
	protoDir := t.TempDir()
	writeFile(t, filepath.Join(protoDir, "authority", "hop", "v1", "policy.proto"), "syntax = \"proto3\";\npackage authority.hop.v1;\n  option go_package = \"github.com/codefly-dev/authority/libraries/hop/go/gen/authority/hop/v1;hopv1\";\n")
	writeFile(t, filepath.Join(protoDir, "records", "v1", "api.proto"), "syntax = \"proto3\";\npackage records.v1;\noption go_package = \"github.com/acme/records/code/pkg/gen/records/v1;recordsv1\";\n")
	requires := []string{"github.com/codefly-dev/authority/libraries/hop/go"}
	for _, c := range []struct {
		source   string
		requires []string
		want     bool
	}{
		{"authority/hop/v1/policy.proto", requires, true},
		{"authority/hop/v1/policy.proto", nil, false},
		{"records/v1/api.proto", requires, false},
		{"codefly/base/v0/agent.proto", nil, true},
		{"missing/v1/gone.proto", requires, true},
	} {
		got, err := mayBeForeign(goBinding{source: c.source}, c.requires, protoDir)
		require.NoError(t, err)
		require.Equal(t, c.want, got, c.source)
	}
}
