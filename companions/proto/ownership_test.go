func writeFile(t *testing.T, file, contents string) {
	t.Helper()
	require.NoError(t, os.MkdirAll(filepath.Dir(file), 0o755))
	require.NoError(t, os.WriteFile(file, []byte(contents), 0o644))
}

// `codefly generate permissions` writes its table into the service's pkg/gen,
// beside Buf's bindings. Cleaning Buf's output before a generation must leave
// that table alone, or every sync deletes it and the service stops compiling.
func TestBufCleanGeneratedDirsKeepsAnotherGeneratorsFiles(t *testing.T) {
	root := t.TempDir()
	generated := filepath.Join(root, "code", "pkg", "gen")
	permissionsGo := "// Code generated by codefly generate permissions. DO NOT EDIT.\npackage permissions\n"
	permissionsTS := "// Code generated by codefly generate permissions. DO NOT EDIT.\nexport const Permission = {};\n"
	writeFile(t, filepath.Join(generated, "permissions", "permissions_gen.go"), permissionsGo)
	writeFile(t, filepath.Join(generated, "permissions", "permissions_gen.ts"), permissionsTS)
	// Buf's own bindings, a stale one from a renamed package among them.
	writeFile(t, filepath.Join(generated, "records", "v1", "api.pb.go"), "// Code generated by protoc-gen-go. DO NOT EDIT.\n// source: records/v1/api.proto\n\npackage v1\n")
	writeFile(t, filepath.Join(generated, "old", "v0", "genconnect", "api.connect.go"), "// Code generated by protoc-gen-connect-go. DO NOT EDIT.\n//\n// Source: old/v0/api.proto\n\npackage genconnect\n")
	// No notice: Buf's, as before.
	writeFile(t, filepath.Join(generated, "api.swagger.json"), "{}\n")
	// A notice quoted in the body is not the file's own.
	writeFile(t, filepath.Join(generated, "quoted", "doc.go"), "package quoted\n\n// Code generated by codefly generate permissions. DO NOT EDIT.\n")
	require.NoError(t, os.Symlink(filepath.Join(generated, "permissions", "permissions_gen.go"), filepath.Join(generated, "linked.go")))

	generator, err := NewBuf(context.Background(), root)
	require.NoError(t, err)
	generator.WithGeneratedDirs(generated)
	require.NoError(t, generator.cleanGeneratedDirs())

	var left []string
	require.NoError(t, filepath.Walk(generated, func(file string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(generated, file)
		left = append(left, filepath.ToSlash(rel))
		return nil
	}))
	require.Equal(t, []string{".", "permissions", "permissions/permissions_gen.go", "permissions/permissions_gen.ts"}, left)
	got, err := os.ReadFile(filepath.Join(generated, "permissions", "permissions_gen.go"))
	require.NoError(t, err)
	require.Equal(t, permissionsGo, string(got))
}

func fileDescriptor(name, pkg string) *descriptorpb.FileDescriptorProto {
	return &descriptorpb.FileDescriptorProto{Name: googleproto.String(name), Package: googleproto.String(pkg)}
}

// A service vendors codefly's protos and the hop option to compile; buf
// generates every file of the module, so their Go bindings came out again in
// the service. IsForeignFile decides, by path and package together, and only Go
// output is touched.
func TestRemoveForeignBindingsKeepsTheServicesOwnGo(t *testing.T) {
	root := t.TempDir()
	goOut := filepath.Join(root, "code", "pkg", "gen")
	tsOut := filepath.Join(root, "frontend", "gen")
	binding := func(rel, generator, sourceLine string) string {
		file := filepath.Join(goOut, rel)
		writeFile(t, file, "// Code generated by "+generator+". DO NOT EDIT.\n// versions:\n// \tprotoc-gen-go v1.36.11\n"+sourceLine+"\n\npackage x\n")
		return file
	}
	own := binding("records/v1/api.pb.go", "protoc-gen-go", "// source: records/v1/api.proto")
	ownGRPC := binding("records/v1/api_grpc.pb.go", "protoc-gen-go-grpc", "// source: records/v1/api.proto")
	ownConnect := binding("records/v1/genconnect/api.connect.go", "protoc-gen-connect-go", "// Source: records/v1/api.proto")
	// A file the module keeps under codefly/ in its own package is its own.
	ownUnderCodefly := binding("codefly/notes/notes.pb.go", "protoc-gen-go", "// source: codefly/notes/notes.proto")
	binding("codefly/base/v0/agent.pb.go", "protoc-gen-go", "// source: codefly/base/v0/agent.proto")
	binding("codefly/runnable/v0/options.pb.go", "protoc-gen-go", "// source: codefly/runnable/v0/options.proto")
	binding("authority/hop/v1/policy.pb.go", "protoc-gen-go", "// source: authority/hop/v1/policy.proto")
	binding("authority/hop/v1/genconnect/policy.connect.go", "protoc-gen-connect-go", "// Source: authority/hop/v1/policy.proto")
	permissions := filepath.Join(goOut, "permissions", "permissions_gen.go")
	writeFile(t, permissions, "// Code generated by codefly generate permissions. DO NOT EDIT.\npackage permissions\n")
	// TypeScript still owns its copy of codefly's protos.
	tsCopy := filepath.Join(tsOut, "codefly", "base", "v0", "agent_pb.ts")
	writeFile(t, tsCopy, "// @generated by protoc-gen-es v2.2.3\n// source: codefly/base/v0/agent.proto\nexport {};\n")

	set := &descriptorpb.FileDescriptorSet{File: []*descriptorpb.FileDescriptorProto{
		fileDescriptor("records/v1/api.proto", "records.v1"),
		fileDescriptor("codefly/notes/notes.proto", "records.notes"),
		fileDescriptor("codefly/base/v0/agent.proto", "codefly.base.v0"),
		fileDescriptor("codefly/runnable/v0/options.proto", "codefly.runnable.v0"),
		fileDescriptor("authority/hop/v1/policy.proto", "authority.hop.v1"),
	}}
	roots := []string{goOut}
	bindings, err := goBindings(roots)
	require.NoError(t, err)
	require.Len(t, bindings, 8)
	require.NoError(t, removeForeignBindings(roots, bindings, foreignGoFiles(set)))

	for _, kept := range []string{own, ownGRPC, ownConnect, ownUnderCodefly, permissions, tsCopy} {
		require.FileExists(t, kept)
	}
	for _, gone := range []string{"codefly/base", "codefly/runnable", "authority"} {
		require.NoDirExists(t, filepath.Join(goOut, gone))
	}
}

func TestOnlyAForeignNamespacePathNeedsItsPackageRead(t *testing.T) {
	require.True(t, inForeignNamespacePath("codefly/base/v0/agent.proto"))
	require.True(t, inForeignNamespacePath("authority/hop/v1/policy.proto"))
	require.True(t, inForeignNamespacePath("google/api/annotations.proto"))
	require.False(t, inForeignNamespacePath("records/v1/api.proto"))
	require.False(t, inForeignNamespacePath("authority/v1/issuer.proto"))
}
